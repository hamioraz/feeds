#!/usr/bin/env python3
"""Add an item to an RSS 2.0 feed file, keeping the newest N items.

Usage:
  python3 add_item.py --feed briefing.xml --title "..." --link "..." \
      --body-file body.html [--guid ID] [--max-items 50] \
      [--channel-title "..."] [--channel-link "..."] [--channel-desc "..."]

The body is treated as HTML and escaped into <description>, which RSS
readers render. The feed is validated by re-parsing before it's written.
"""
import argparse
import hashlib
import os
import sys
import tempfile
import xml.etree.ElementTree as ET
from datetime import datetime, timezone
from email.utils import format_datetime

ATOM = "http://www.w3.org/2005/Atom"
ET.register_namespace("atom", ATOM)


def new_feed(title, link, desc, self_url):
    rss = ET.Element("rss", {"version": "2.0"})
    ch = ET.SubElement(rss, "channel")
    ET.SubElement(ch, "title").text = title
    ET.SubElement(ch, "link").text = link
    ET.SubElement(ch, "description").text = desc
    ET.SubElement(ch, "language").text = "en-au"
    if self_url:
        ET.SubElement(ch, f"{{{ATOM}}}link",
                      {"href": self_url, "rel": "self", "type": "application/rss+xml"})
    return ET.ElementTree(rss)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--feed", required=True)
    p.add_argument("--title", required=True)
    p.add_argument("--link", required=True)
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--body")
    g.add_argument("--body-file")
    p.add_argument("--guid")
    p.add_argument("--max-items", type=int, default=50)
    p.add_argument("--channel-title", default="Feed")
    p.add_argument("--channel-link", default="https://example.com/")
    p.add_argument("--channel-desc", default="Generated by a Claude scheduled task")
    p.add_argument("--self-url", default="")
    a = p.parse_args()

    body = a.body if a.body is not None else open(a.body_file, encoding="utf-8").read()
    if not body.strip():
        sys.exit("error: empty body")

    if os.path.exists(a.feed):
        tree = ET.parse(a.feed)
    else:
        tree = new_feed(a.channel_title, a.channel_link, a.channel_desc, a.self_url)
    ch = tree.getroot().find("channel")
    if ch is None:
        sys.exit("error: feed has no <channel>")

    now = datetime.now(timezone.utc)
    guid = a.guid or hashlib.sha256(f"{a.title}|{now.isoformat()}".encode()).hexdigest()[:16]

    # Idempotent: replace an existing item with the same guid instead of duplicating.
    for old in ch.findall("item"):
        if (old.findtext("guid") or "") == guid:
            ch.remove(old)

    item = ET.Element("item")
    ET.SubElement(item, "title").text = a.title
    ET.SubElement(item, "link").text = a.link
    ET.SubElement(item, "guid", {"isPermaLink": "false"}).text = guid
    ET.SubElement(item, "pubDate").text = format_datetime(now)
    ET.SubElement(item, "description").text = body

    # Insert newest first, after channel metadata.
    items = ch.findall("item")
    idx = list(ch).index(items[0]) if items else len(ch)
    ch.insert(idx, item)
    for extra in ch.findall("item")[a.max_items:]:
        ch.remove(extra)

    lbd = ch.find("lastBuildDate")
    if lbd is None:
        lbd = ET.SubElement(ch, "lastBuildDate")
    lbd.text = format_datetime(now)

    ET.indent(tree)
    data = ET.tostring(tree.getroot(), encoding="utf-8", xml_declaration=True)
    ET.fromstring(data)  # validate before writing

    d = os.path.dirname(os.path.abspath(a.feed))
    fd, tmp = tempfile.mkstemp(dir=d, suffix=".tmp")
    with os.fdopen(fd, "wb") as f:
        f.write(data)
    os.replace(tmp, a.feed)
    print(f"ok: {a.feed} now has {len(ch.findall('item'))} item(s); guid={guid}")


if __name__ == "__main__":
    main()
